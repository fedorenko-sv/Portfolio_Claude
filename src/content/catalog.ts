export type Catalog = {
  cases: Case[];
  programs: Program[];
  materials: Material[];
};
export function catalogFor(
  stage: string = process.env.VERCEL_ENV ??
    (process.env.NODE_ENV === "development" ? "preview" : "production"),
): Catalog {
  return {
    cases: cases.filter((x) => x.published),
    materials: materials.filter((x) => x.published),
    programs: programs.filter(
      (x) =>
        (x.published && x.approvalStatus === "approved") ||
        (stage !== "production" && x.approvalStatus === "draft"),
    ),
  };
}
export function validateCatalog(catalog: Catalog): void {
  function validUrl(value: string) {
    try {
      const url = new URL(value);
      if (url.protocol !== "https:" || url.username || url.password)
        throw new Error();
    } catch {
      throw new Error("Invalid URL");
    }
  }
  for (const list of [catalog.cases, catalog.programs, catalog.materials]) {
    const slugs = new Set<string>();
    for (const item of list) {
      if (!/^[a-z0-9-]+$/.test(item.slug) || slugs.has(item.slug))
        throw new Error("Invalid or duplicate slug");
      slugs.add(item.slug);
      if (!item.title || !item.id || typeof item.published !== "boolean")
        throw new Error("Missing content fields");
    }
  }
  for (const item of catalog.cases) {
    if (
      !["prototype", "demo", "pilot", "production"].includes(item.status) ||
      !item.limitations.length ||
      !item.problem
    )
      throw new Error("Invalid case");
    for (const url of item.evidence) validUrl(url);
  }
  for (const item of catalog.materials) {
    if (item.steps.length < 3 || !item.example || !item.checklist.length)
      throw new Error("Incomplete material");
    for (const url of item.sourceUrls) validUrl(url);
  }
}
validateCatalog({ cases, programs, materials });
